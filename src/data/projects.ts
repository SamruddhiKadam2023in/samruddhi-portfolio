import type { Project, ProjectImage } from '../types/project';

/** Builds an image entry for /images/<project>/<file>.webp (sizes from scripts/optimize-images.mjs). */
function shot(
  project: string,
  file: string,
  width: number,
  height: number,
  alt: string,
  caption: string,
): ProjectImage {
  return { src: `/images/${project}/${file}.webp`, width, height, alt, caption };
}

